-- Supabase/PostgreSQL schema for CampusDesk.
-- Keep this schema isolated from other projects sharing the same Supabase database.
CREATE SCHEMA IF NOT EXISTS campusdesk;

CREATE TABLE IF NOT EXISTS campusdesk.departments (
  department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department_name VARCHAR(100) NOT NULL UNIQUE,
  department_code VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS campusdesk.students (
  student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roll_no VARCHAR(30) NOT NULL UNIQUE,
  first_name VARCHAR(60) NOT NULL,
  last_name VARCHAR(60) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  phone VARCHAR(25),
  date_of_birth DATE,
  gender VARCHAR(20),
  admission_date DATE NOT NULL DEFAULT CURRENT_DATE,
  department_id BIGINT REFERENCES campusdesk.departments(department_id) ON DELETE SET NULL,
  semester SMALLINT NOT NULL DEFAULT 1 CHECK (semester BETWEEN 1 AND 12),
  status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE','GRADUATED')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_campusdesk_students_name ON campusdesk.students(last_name, first_name);
CREATE INDEX IF NOT EXISTS idx_campusdesk_students_department ON campusdesk.students(department_id);

CREATE TABLE IF NOT EXISTS campusdesk.faculty (
  faculty_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  faculty_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  department_id BIGINT REFERENCES campusdesk.departments(department_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS campusdesk.courses (
  course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_code VARCHAR(20) NOT NULL UNIQUE,
  course_name VARCHAR(120) NOT NULL,
  credits SMALLINT NOT NULL DEFAULT 3 CHECK (credits BETWEEN 1 AND 10),
  department_id BIGINT REFERENCES campusdesk.departments(department_id) ON DELETE SET NULL,
  faculty_id BIGINT REFERENCES campusdesk.faculty(faculty_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS campusdesk.enrollments (
  enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES campusdesk.students(student_id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES campusdesk.courses(course_id) ON DELETE CASCADE,
  academic_year VARCHAR(9) NOT NULL CHECK (academic_year ~ '^20[0-9]{2}-[0-9]{2}$'),
  semester SMALLINT NOT NULL CHECK (semester BETWEEN 1 AND 12),
  enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_campusdesk_enrollment UNIQUE(student_id, course_id, academic_year, semester)
);
CREATE INDEX IF NOT EXISTS idx_campusdesk_enrollment_course ON campusdesk.enrollments(course_id);

CREATE TABLE IF NOT EXISTS campusdesk.attendance (
  attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id BIGINT NOT NULL REFERENCES campusdesk.enrollments(enrollment_id) ON DELETE CASCADE,
  attendance_date DATE NOT NULL,
  attendance_status VARCHAR(10) NOT NULL CHECK (attendance_status IN ('PRESENT','ABSENT','LATE','EXCUSED')),
  CONSTRAINT uq_campusdesk_attendance_day UNIQUE(enrollment_id, attendance_date)
);
CREATE INDEX IF NOT EXISTS idx_campusdesk_attendance_date ON campusdesk.attendance(attendance_date);

CREATE TABLE IF NOT EXISTS campusdesk.assessments (
  assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  course_id BIGINT NOT NULL REFERENCES campusdesk.courses(course_id) ON DELETE CASCADE,
  assessment_name VARCHAR(100) NOT NULL,
  max_marks NUMERIC(6,2) NOT NULL CHECK (max_marks > 0),
  assessment_date DATE
);

CREATE TABLE IF NOT EXISTS campusdesk.marks (
  mark_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assessment_id BIGINT NOT NULL REFERENCES campusdesk.assessments(assessment_id) ON DELETE CASCADE,
  student_id BIGINT NOT NULL REFERENCES campusdesk.students(student_id) ON DELETE CASCADE,
  marks_obtained NUMERIC(6,2) NOT NULL CHECK (marks_obtained >= 0),
  CONSTRAINT uq_campusdesk_assessment_student UNIQUE(assessment_id, student_id)
);

CREATE TABLE IF NOT EXISTS campusdesk.admin_users (
  admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
