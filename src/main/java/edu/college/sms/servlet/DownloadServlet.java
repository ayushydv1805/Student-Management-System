package edu.college.sms.servlet;

import jakarta.servlet.ServletException;
import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.io.InputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.time.Duration;
import java.util.Locale;

/**
 * Streams installer files through the application's own HTTPS host.
 *
 * This avoids sharing short-lived file URLs generated by chat tools. The source
 * is a stable GitHub Release URL; this servlet streams bytes instead of
 * redirecting the browser to the upstream file host.
 */
@WebServlet(urlPatterns = {"/download/windows", "/download/android"})
public class DownloadServlet extends HttpServlet {
    private static final String WINDOWS_URL =
        "https://github.com/ayushydv1805/Student-Management-System/releases/download/campusdesk-v1.0.0/CampusDesk-Setup.exe";
    private static final String ANDROID_URL =
        "https://github.com/ayushydv1805/Student-Management-System/releases/download/campusdesk-v1.0.0/CampusDesk.apk";

    private static final HttpClient HTTP = HttpClient.newBuilder()
        .connectTimeout(Duration.ofSeconds(20))
        .followRedirects(HttpClient.Redirect.ALWAYS)
        .build();

    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        String path = request.getServletPath();
        final String source;
        final String filename;
        final String contentType;

        if ("/download/windows".equals(path)) {
            source = WINDOWS_URL;
            filename = "CampusDesk-Setup.exe";
            contentType = "application/vnd.microsoft.portable-executable";
        } else if ("/download/android".equals(path)) {
            source = ANDROID_URL;
            filename = "CampusDesk.apk";
            contentType = "application/vnd.android.package-archive";
        } else {
            response.sendError(HttpServletResponse.SC_NOT_FOUND);
            return;
        }

        HttpRequest.Builder builder = HttpRequest.newBuilder(URI.create(source))
            .timeout(Duration.ofMinutes(4))
            .header("User-Agent", "CampusDesk-Download-Proxy/1.0")
            .header("Accept", "application/octet-stream")
            .GET();

        // Preserve Range requests for browsers/download managers that resume a download.
        String range = request.getHeader("Range");
        if (range != null && !range.isBlank()) {
            builder.header("Range", range);
        }

        try {
            HttpResponse<InputStream> upstream =
                HTTP.send(builder.build(), HttpResponse.BodyHandlers.ofInputStream());
            int upstreamStatus = upstream.statusCode();

            if (upstreamStatus != HttpServletResponse.SC_OK
                    && upstreamStatus != HttpServletResponse.SC_PARTIAL_CONTENT) {
                try (InputStream ignored = upstream.body()) {
                    // Close the upstream response without exposing its error page.
                }
                getServletContext().log("CampusDesk download source returned HTTP " + upstreamStatus
                    + " for " + filename);
                response.setStatus(HttpServletResponse.SC_SERVICE_UNAVAILABLE);
                response.setContentType("text/plain; charset=UTF-8");
                response.setHeader("Cache-Control", "no-store");
                response.getWriter().write(
                    "CampusDesk download is temporarily unavailable. Please try again shortly, "
                    + "or use the stable release page at "
                    + "https://github.com/ayushydv1805/Student-Management-System/releases/tag/campusdesk-v1.0.0");
                return;
            }

            response.setStatus(upstreamStatus);
            response.setContentType(contentType);
            response.setHeader("Content-Disposition", "attachment; filename=\"" + filename + "\"");
            response.setHeader("X-Content-Type-Options", "nosniff");
            response.setHeader("Cache-Control", "public, max-age=3600");
            response.setHeader("Accept-Ranges", "bytes");

            upstream.headers().firstValue("Content-Length")
                .ifPresent(value -> response.setHeader("Content-Length", value));
            upstream.headers().firstValue("Content-Range")
                .ifPresent(value -> response.setHeader("Content-Range", value));
            upstream.headers().firstValue("ETag")
                .ifPresent(value -> response.setHeader("ETag", value));

            try (InputStream body = upstream.body()) {
                body.transferTo(response.getOutputStream());
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            response.setStatus(HttpServletResponse.SC_SERVICE_UNAVAILABLE);
            response.setContentType("text/plain; charset=UTF-8");
            response.getWriter().write("Download was interrupted. Please retry.");
        } catch (IllegalArgumentException e) {
            getServletContext().log("Invalid CampusDesk download source URI.", e);
            response.sendError(HttpServletResponse.SC_BAD_GATEWAY, "Download source could not be reached.");
        }
    }

    @Override
    protected void doHead(HttpServletRequest request, HttpServletResponse response) throws IOException {
        // A lightweight HEAD response lets browsers and download managers check availability.
        String path = request.getServletPath();
        if (!"/download/windows".equals(path) && !"/download/android".equals(path)) {
            response.sendError(HttpServletResponse.SC_NOT_FOUND);
            return;
        }
        String source = "/download/windows".equals(path) ? WINDOWS_URL : ANDROID_URL;
        String filename = "/download/windows".equals(path) ? "CampusDesk-Setup.exe" : "CampusDesk.apk";
        response.setStatus(HttpServletResponse.SC_OK);
        response.setHeader("Content-Disposition", "attachment; filename=\"" + filename + "\"");
        response.setHeader("Cache-Control", "no-store");
        response.setHeader("X-Download-Source", "CampusDesk");
        response.setHeader("Link", "<" + source + ">; rel=\"describedby\"");
    }
}
